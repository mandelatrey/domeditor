// Compiles src/client/styles.css with Tailwind into src/client/styles.generated.ts (a string the
// shadow root adopts). Shadow roots ignore @property rules, which Tailwind relies on for the initial
// values of its --tw-* variables (shadows, rings, transforms), so those values are added as plain
// declarations too.
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync, mkdtempSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import postcss from "postcss";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const out = join(mkdtempSync(join(tmpdir(), "domeditor-")), "styles.css");
execFileSync(process.execPath, [join(root, "node_modules/@tailwindcss/cli/dist/index.mjs"), "-i", join(root, "src/client/styles.css"), "-o", out, "--minify"], { stdio: "inherit" });

const ast = postcss.parse(readFileSync(out, "utf8"));
const initial = [];
ast.walkAtRules("property", (rule) => {
  rule.walkDecls("initial-value", (d) => initial.push(`${rule.params}:${d.value}`));
});
if (initial.length) ast.append(postcss.parse(`@layer properties{:host,*,::before,::after,::backdrop{${initial.join(";")}}}`));

const css = ast.toString();
writeFileSync(join(root, "src/client/styles.generated.ts"), `// Generated by scripts/build-css.mjs from styles.css. Do not edit.\nexport default ${JSON.stringify(css)};\n`);
console.log(`styles.generated.ts: ${(css.length / 1024).toFixed(1)} kB, ${initial.length} @property fallbacks`);
